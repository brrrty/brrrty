// Regenerates src/mime_table.rs: the extension to Content-Type table that
// mime 3.0.0 (the package @11ty/eleventy-dev-server 2.1.2 uses) answers with
// for every extension it knows. Run with Node 20 or later (the file was made
// with v26.2.0), pointing at a node_modules folder that has mime 3:
//
//   node tools/gen-mime-table.cjs path/to/node_modules > src/mime_table.rs
//
const path = require("node:path");
const root = path.resolve(process.argv[2] || "node_modules");
const req = (p) => require(path.join(root, p));
const mime = req("mime");
const exts = new Set();
for (const file of ["mime/types/standard.js", "mime/types/other.js"]) {
  for (const type of Object.values(req(file))) for (const e of type) exts.add(e.replace(/^\*/, ""));
}
const rows = [...exts].sort().map((e) => [e, mime.getType("x." + e)])
  .filter(([, t]) => t);
const out = [];
out.push("// Generated by tools/gen-mime-table.cjs from mime 3.0.0. Do not edit.");
out.push("// Sorted by extension so lookups can binary search.");
out.push("pub(crate) static TYPES: &[(&str, &str)] = &[");
for (const [e, t] of rows) out.push(`    (${JSON.stringify(e)}, ${JSON.stringify(t)}),`);
out.push("];");
console.log(out.join("\n"));
