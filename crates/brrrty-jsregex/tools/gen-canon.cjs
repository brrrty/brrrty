// Regenerates src/canon_table.rs: the ECMAScript Canonicalize operation of a
// regular expression with the `i` flag and without `u` or `v`, as Node runs
// it. For a UTF-16 unit `ch`, Canonicalize is `ch.toUpperCase()` when that is
// one unit, unless `ch` is outside ASCII and the result is in it; otherwise
// `ch` itself. Two units match each other under `i` exactly when their
// canonical units are equal. Only units whose canonical unit differs are
// listed.
//
//   node tools/gen-canon.cjs > src/canon_table.rs
//
// Run from crates/brrrty-jsregex (the file was made with Node v26.2.0).

'use strict';

const pairs = [];
for (let u = 0; u <= 0xffff; u++) {
  const up = String.fromCharCode(u).toUpperCase();
  let c = u;
  if (up.length === 1) {
    const cu = up.charCodeAt(0);
    if (!(u >= 128 && cu < 128)) c = cu;
  }
  if (c !== u) pairs.push([u, c]);
}

// Check the table against the engine itself: `ch` and its canonical unit
// match each other with `i`.
for (const [u, c] of pairs) {
  const esc = (x) => '\\u' + x.toString(16).padStart(4, '0');
  if (!new RegExp('^' + esc(c) + '$', 'i').test(String.fromCharCode(u))) {
    throw new Error(`U+${u.toString(16)} does not match U+${c.toString(16)} with i`);
  }
}

const hex = (x) => '0x' + x.toString(16).toUpperCase().padStart(4, '0');
let out = '';
out += '// Generated by tools/gen-canon.cjs with Node ' + process.version + '. Do not edit.\n\n';
out += '/// `(unit, canonical unit)` for every UTF-16 unit whose canonical unit\n';
out += '/// differs, in unit order.\n';
out += '#[rustfmt::skip]\n';
out += 'pub(crate) static CANON: &[(u16, u16)] = &[\n';
for (let i = 0; i < pairs.length; i += 4) {
  out += '    ' + pairs.slice(i, i + 4).map(([u, c]) => `(${hex(u)}, ${hex(c)})`).join(', ') + ',\n';
}
out += '];\n';
process.stdout.write(out);
