// Regenerates src/uc_micro.rs: markdown-it's `isPunctChar` (uc.micro `P` or `S`) for every code
// point, from uc.micro 3.0.0 (markdown-it 15's) and 2.1.0 (11ty 3.1.8's bundled 14.3.3), and
// uc.micro `Z` or `Cc` for each UTF-16 unit. Run from crates/brrrty-markdown with Node 20 or
// later (the file was made with v26.2.0):
//
//   UC_MICRO=/path/to/uc.micro UC_MICRO_11TY=/path/to/@11ty/eleventy/node_modules/uc.micro \
//     node tools/gen-uc-micro.cjs > src/uc_micro.rs
const load = (dir, want) => {
  if (!dir) throw new Error('set UC_MICRO and UC_MICRO_11TY to the uc.micro package directories');
  const version = require(`${dir}/package.json`).version;
  if (version !== want) throw new Error(`uc.micro ${version} in ${dir}, expected ${want}`);
  return require(dir);
};
const v3 = load(process.env.UC_MICRO, '3.0.0');
const v2 = load(process.env.UC_MICRO_11TY, '2.1.0');

const ranges = (test, max) => {
  const out = [];
  let start = -1;
  for (let u = 0; u <= max + 1; u++) {
    const yes = u <= max && test(String.fromCodePoint(u));
    if (yes && start < 0) start = u;
    if (!yes && start >= 0) { out.push([start, u - 1]); start = -1; }
  }
  return out;
};
const table = (name, type, doc, rs) =>
  `/// ${doc}\npub(crate) const ${name}: &[(${type}, ${type})] = &[\n` +
  rs.map(([a, b]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}),\n`).join('') + '];\n';

let out = '// @generated by tools/gen-uc-micro.cjs from uc.micro 3.0.0 and 2.1.0. Do not edit.\n\n';
out += table('PUNCT_OR_SYMBOL', 'u32', "Code points in uc.micro 3.0.0 `P` or `S`: markdown-it 15's `isPunctChar`.",
  ranges((ch) => v3.P.test(ch) || v3.S.test(ch), 0x10ffff));
out += table('PUNCT_OR_SYMBOL_11TY', 'u32', "Code points in uc.micro 2.1.0 `P` or `S`: markdown-it 14.3.3's `isPunctChar`.",
  ranges((ch) => v2.P.test(ch) || v2.S.test(ch), 0x10ffff));
out += table('SPACE_OR_CONTROL', 'u16', 'UTF-16 units in uc.micro 3.0.0 `Z` or `Cc`.',
  ranges((ch) => v3.Z.test(ch) || v3.Cc.test(ch), 0xffff));
process.stdout.write(out);
