// Regenerates src/linkify_re.rs: linkify-it 6.1.0's compiled patterns, as markdown-it 15 builds
// its instance (`new LinkifyIt()`: the default schemas, TLDs and options; `fuzzyLink` doesn't
// change a pattern). Run from crates/brrrty-markdown with Node 20 or later (the file was made
// with v26.2.0):
//
//   LINKIFY_IT=/path/to/node_modules/linkify-it node tools/gen-linkify.cjs > src/linkify_re.rs
const { LinkifyIt } = require(process.env.LINKIFY_IT || (() => { throw new Error('set LINKIFY_IT to the linkify-it package directory (6.1.0)'); })());
const version = require(`${process.env.LINKIFY_IT}/package.json`).version;
if (version !== '6.1.0') throw new Error(`linkify-it ${version}, expected 6.1.0`);

const l = new LinkifyIt();
const patterns = [
  ['SCHEMA_SEARCH', 'get_schema_search', 'gi', 'Finds a schema name after a boundary.'],
  ['SCHEMA_AT_START', 'get_schema_at_start', 'i', '`SCHEMA_SEARCH` at the start of the text.'],
  ['FUZZY_LINK_SEARCH', 'get_fuzzy_link_search', 'gi', 'A link without a schema (`fuzzyLink`).'],
  ['FUZZY_MAIL_HOST_SEARCH', 'get_fuzzy_mail_host_search', 'gi', '`@` and an email host (`fuzzyEmail`).'],
  ['MAIL_NAME_VALIDATOR', 'get_mail_name_validator', '', 'The name before an email host.'],
  ['HTTP_VALIDATOR', 'get_http_validator', 'iy', 'What follows `http:`, `https:` and `ftp:`.'],
  ['RELATIVE_PROTO_VALIDATOR', 'get_relative_proto_validator', 'iy', 'What follows `//`.'],
  ['MAILTO_VALIDATOR', 'get_mailto_validator', 'iy', 'What follows `mailto:`.'],
];
let out = `// @generated by tools/gen-linkify.cjs from linkify-it ${version}. Do not edit.\n`;
out += '//\n// Each is `(source, flags)`, as JavaScript has them.\n';
for (const [name, getter, flags, doc] of patterns) {
  const re = l.re[getter]();
  if (re.flags !== flags) throw new Error(`${getter}: flags ${re.flags}, expected ${flags}`);
  if (re.source.includes('"#') || /[\0-\x1f]/.test(re.source)) throw new Error(`${getter} needs escaping`);
  out += `\n/// ${doc}\npub(crate) const ${name}: (&str, &str) = (\n    r#"${re.source}"#,\n    "${flags}",\n);\n`;
}
process.stdout.write(out);
