// Generates src/helpers/luxon_zones.rs: the zone names Luxon prints for IANA
// zones (ZZZZ, ZZZZZ, and the macro tokens ttt, tttt and so on), as Node
// (ICU) gives them.
//
//   node tools/gen-luxon-zones.mjs /usr/share/zoneinfo > src/helpers/luxon_zones.rs && rustfmt src/helpers/luxon_zones.rs
//
// For each zone in the tz database directory that Node accepts it records
//   - ALIASES: the lower-cased name, the name as the tz database spells it,
//     and the id ICU resolves it to; and
//   - NAMES: for each ICU id, the short and long name for each UTC offset
//     seen from 1970 to 2038. An offset that had different names in that time
//     gets the latest one, with the time (ms, 15 days after the sample that
//     first showed it) from which it applies; the formatter refuses earlier
//     instants. A name that is only the "GMT+5:30" fallback form, with
//     nothing earlier, is left out; the formatter produces it.
import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: gen-luxon-zones.mjs <zoneinfo dir>');

function walk(dir, prefix, out) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    const id = prefix ? `${prefix}/${name}` : name;
    if (st.isDirectory()) {
      if (['posix', 'right', 'Etc.d'].includes(name)) continue;
      walk(full, id, out);
    } else if (/^[A-Z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+)*$/.test(id)) {
      out.push(id);
    }
  }
  return out;
}

const gmtShort = (o) => {
  if (o === 0) return 'GMT';
  const a = Math.abs(o), h = Math.floor(a / 60), m = a % 60;
  return `GMT${o < 0 ? '-' : '+'}${h}${m ? ':' + String(m).padStart(2, '0') : ''}`;
};
const gmtLong = (o) => {
  if (o === 0) return 'GMT';
  const a = Math.abs(o), h = Math.floor(a / 60), m = a % 60;
  return `GMT${o < 0 ? '-' : '+'}${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
};

const zones = walk(root, '', []).sort();
const aliases = [];
const names = new Map();
for (const zone of zones) {
  let dtf;
  try { dtf = new Intl.DateTimeFormat('en-US', { timeZone: zone }); } catch { continue; }
  const id = dtf.resolvedOptions().timeZone;
  aliases.push([zone.toLowerCase(), zone, id]);
  if (names.has(id)) continue;
  const mk = (style) => new Intl.DateTimeFormat('en-US', { timeZone: zone, hourCycle: 'h23', hour: '2-digit', minute: '2-digit', timeZoneName: style });
  const short = mk('short'), long = mk('long');
  const part = (f, d) => f.formatToParts(d).find((p) => p.type === 'timeZoneName').value;
  const off = new Intl.DateTimeFormat('en-US', { timeZone: zone, hourCycle: 'h23', year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric', second: 'numeric' });
  const byOffset = new Map();
  for (let y = 1970; y <= 2038; y++) {
    for (let m = 0; m < 12; m++) {
      for (const day of [1, 15]) {
        const d = new Date(Date.UTC(y, m, day, 12));
        const p = Object.fromEntries(off.formatToParts(d).map((x) => [x.type, x.value]));
        const local = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute, +p.second);
        const o = Math.round((local - d.getTime()) / 60000);
        const entry = [part(short, d), part(long, d)];
        const prev = byOffset.get(o);
        if (!prev) byOffset.set(o, [...entry, 0]);
        else if (prev[0] !== entry[0] || prev[1] !== entry[1]) byOffset.set(o, [...entry, d.getTime() + 15 * 86400000]);
      }
    }
  }
  names.set(id, [...byOffset].filter(([o, [s, l, since]]) => since !== 0 || s !== gmtShort(o) || l !== gmtLong(o)).sort((a, b) => a[0] - b[0]));
}

const q = (s) => JSON.stringify(s);
console.log('// Generated by tools/gen-luxon-zones.mjs. Do not edit.');
console.log(`// Names are those of Node ${process.version} (ICU ${process.versions.icu}).`);
console.log('');
console.log('/// `(lower-cased name, name as the tz database spells it, id ICU resolves it to)`, sorted by the first.');
console.log('pub(super) static ALIASES: &[(&str, &str, &str)] = &[');
for (const [l, z, id] of aliases.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))) console.log(`    (${q(l)}, ${q(z)}, ${q(id)}),`);
console.log('];');
console.log('');
console.log('/// `(id, [(offset in minutes east of UTC, short name, long name, applies from ms)])`, sorted by id.');
console.log('pub(super) type Name = (i16, &\'static str, &\'static str, i64);');
console.log('pub(super) static NAMES: &[(&str, &[Name])] = &[');
for (const id of [...names.keys()].sort()) {
  const items = names.get(id).map(([o, [s, l, since]]) => `(${o}, ${q(s)}, ${q(l)}, ${since})`).join(', ');
  if (items) console.log(`    (${q(id)}, &[${items}]),`);
}
console.log('];');
