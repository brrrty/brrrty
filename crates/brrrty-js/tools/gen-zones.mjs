// Generates src/zones.rs: the time zone names Node (ICU) prints.
//
//   node tools/gen-zones.mjs /usr/share/zoneinfo > src/zones.rs
//
// For every zone in the tz database directory it records
//   - the id Node reports for it (`Intl.DateTimeFormat().resolvedOptions().timeZone`),
//     which is what LiquidJS prints for `%Z`, and
//   - the long name `Date.prototype.toString()` prints in parentheses, for each
//     UTC offset seen from 1970 to 2038. When an offset had several names the
//     most recent one wins.
import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: gen-zones.mjs <zoneinfo dir>');

function walk(dir, prefix, out) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    const id = prefix ? `${prefix}/${name}` : name;
    if (st.isDirectory()) {
      if (['posix', 'right', 'Etc.d'].includes(name)) continue;
      walk(full, id, out);
    } else if (/^[A-Z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+)*$/.test(id)) {
      out.push(id);
    }
  }
  return out;
}

const zones = walk(root, '', []).sort();
const aliases = [];
const profiles = new Map();
for (const zone of zones) {
  process.env.TZ = zone;
  const resolved = Intl.DateTimeFormat().resolvedOptions().timeZone;
  if (resolved === undefined) continue; // Node does not know this zone.
  aliases.push([zone, resolved]);
  const byOffset = new Map();
  for (let y = 1970; y <= 2038; y++) {
    for (let m = 0; m < 12; m++) {
      const d = new Date(Date.UTC(y, m, 15, 12));
      const s = d.toString();
      const name = s.slice(s.indexOf('(') + 1, s.lastIndexOf(')'));
      byOffset.set(-d.getTimezoneOffset(), name);
    }
  }
  const entries = [...byOffset].sort((a, b) => a[0] - b[0]);
  const prev = profiles.get(resolved);
  if (!prev || zone === resolved) profiles.set(resolved, entries);
}

const q = (s) => JSON.stringify(s);
console.log('// Generated by tools/gen-zones.mjs. Do not edit.');
console.log(`// Names are those of Node ${process.version} (ICU ${process.versions.icu}).`);
console.log('');
console.log('/// `(zone as written in TZ, id Node reports for it)`, sorted by zone.');
console.log('pub(crate) static ZONE_IDS: &[(&str, &str)] = &[');
for (const [z, id] of aliases) console.log(`    (${q(z)}, ${q(id)}),`);
console.log('];');
console.log('');
console.log('/// `(id, [(offset in minutes east of UTC, long name)])`, sorted by id.');
console.log('pub(crate) static PROFILES: &[(&str, &[(i16, &str)])] = &[');
for (const id of [...profiles.keys()].sort()) {
  const items = profiles.get(id).map(([o, n]) => `(${o}, ${q(n)})`).join(', ');
  console.log(`    (${q(id)}, &[${items}]),`);
}
console.log('];');
