    'Ä', 'ä', 'Ö ö Ü ü', 'Ç ç', 'Ğ ğ İ ı Ş ş', '©2024 ® ™', '€ £ ¥ ¢', '½ ¼ ¾', 'x² y³', '→ ← ↑', '\u200bzero\u200bwidth',
