    '', ' ', '-', '_', '___', '2024', '0', 'ABC123def', 'x@y.com', 'a/b/c', '(parens) [brackets] {braces}',
    'tilde~star*plus+', '!bang!', 'colon: semi; comma,', 'ǅ ǆ Ǉ', 'İstanbul', 'K Kelvin', 'ﬁ ligature',
